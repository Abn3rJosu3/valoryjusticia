CREATE TABLE EXPEDIENTES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_EXPEDIENTE VARCHAR2(50) UNIQUE NOT NULL,
    ID_CONTACTO NUMBER, -- Opcional: para enlazarlo con el mensaje inicial de CONTACTOS
    CLIENTE VARCHAR2(150) NOT NULL,
    ABOGADO_RESPONSABLE VARCHAR2(150) NOT NULL,
    ESTADO VARCHAR2(50) DEFAULT 'En Trámite', -- Valores: En Trámite, Audiencia Pendiente, Finalizado, Archivado
    DESCRIPCION CLOB,
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT fk_contacto FOREIGN KEY (ID_CONTACTO) REFERENCES CONTACTOS(ID)
);

